"""
Нормализация данных о компаниях для дедупликации (Sprint 1 — FR-1.1, FR-1.4).

Разные источники (HH.ru, ручной ввод, импорт из CSV) могут указывать
одну и ту же компанию по-разному:
  - "ООО «Ромашка»" / "Ромашка" / "ооо ромашка"
  - "Екатеринбург" / "г. Екатеринбург" / "г.Екатеринбург"

Функции в этом модуле приводят такие значения к каноническому виду,
чтобы CompanyRepository.upsert_by_name мог находить дубликаты не только
по точному совпадению имени, но и по нормализованному.
"""
import re

# Организационно-правовые формы (рус. + англ.), которые отбрасываются
# при нормализации названия компании. Сортировка по длине (длинные
# сначала) не обязательна — паттерн собирается как набор отдельных слов.
_LEGAL_FORMS = [
    "ооо", "оао", "зао", "пао", "ао", "нко", "одо", "тоо", "ип",
    "учреждение", "фонд", "корпорация",
    "llc", "ltd", "inc", "jsc", "corp", "co", "gmbh", "plc",
]

_LEGAL_FORMS_RE = re.compile(
    r"\b(?:" + "|".join(re.escape(f) for f in _LEGAL_FORMS) + r")\b",
    flags=re.IGNORECASE,
)

# Кавычки и прочие декоративные символы, которые часто встречаются
# в названиях компаний из разных источников.
_QUOTES_RE = re.compile(r"[«»\"'“”‘’`]")

# Любые символы, кроме букв (включая кириллицу), цифр и пробелов.
_PUNCT_RE = re.compile(r"[^\w\s]", flags=re.UNICODE)

_WHITESPACE_RE = re.compile(r"\s+")


def normalize_company_name(name: str | None) -> str:
    """
    Приводит название компании к каноническому виду для сравнения.

    Пример:
        normalize_company_name('ООО "Ромашка"')       -> "ромашка"
        normalize_company_name("Ромашка")              -> "ромашка"
        normalize_company_name("  ромашка  ")          -> "ромашка"

    Возвращает пустую строку, если на входе None/пустая строка.
    """
    if not name:
        return ""

    value = name.strip().lower()
    value = _QUOTES_RE.sub(" ", value)
    value = _LEGAL_FORMS_RE.sub(" ", value)
    value = _PUNCT_RE.sub(" ", value)
    value = _WHITESPACE_RE.sub(" ", value).strip()
    return value


# Частые варианты написания регионов -> канонический вид.
# Ключи — уже в нижнем регистре, без знаков пунктуации (после _PUNCT_RE),
# чтобы сравнение было устойчивым к "г. Екатеринбург", "г Екатеринбург" и т.п.
_REGION_ALIASES: dict[str, str] = {
    "екатеринбург": "Екатеринбург",
    "г екатеринбург": "Екатеринбург",
    "город екатеринбург": "Екатеринбург",
    "свердловская область": "Свердловская область",
    "свердловская обл": "Свердловская область",
    "москва": "Москва",
    "г москва": "Москва",
    "город москва": "Москва",
    "московская область": "Московская область",
    "санкт-петербург": "Санкт-Петербург",
    "санкт петербург": "Санкт-Петербург",
    "спб": "Санкт-Петербург",
    "г санкт петербург": "Санкт-Петербург",
}


def normalize_region(region: str | None) -> str | None:
    """
    Приводит название региона к каноническому виду по словарю синонимов.

    Если регион не найден в словаре — возвращает исходное значение
    с обрезанными пробелами (без потери данных для неизвестных регионов).
    """
    if not region:
        return region

    cleaned = _WHITESPACE_RE.sub(" ", _PUNCT_RE.sub(" ", region.strip().lower())).strip()
    return _REGION_ALIASES.get(cleaned, region.strip())
